from __future__ import annotations

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

router = Router(name="faq")

FAQ_TEXT = (
    "❓ Как считается рейтинг\n\n"
    "Мы используем систему Glicko-2 — она сложнее обычного Эло, но даёт более "
    "честную оценку, особенно для новичков и тех, кто давно не играл.\n\n"
    "У каждого игрока есть три числа:\n"
    "• Рейтинг — сила игры (старт 1500).\n"
    "• RD (rating deviation) — «неуверенность» в рейтинге. У новичка RD большой "
    "(350) — система ещё мало о нём знает. Чем больше сыграно матчей, тем RD ниже.\n"
    "• σ (волатильность) — насколько нестабильно играет человек.\n\n"
    "Правила:\n"
    "1. Победа над сильным соперником даёт больше очков, чем победа над слабым.\n"
    "2. Если вы долго не играли — ваш RD подрастает, и следующий матч сильнее "
    "повлияет на рейтинг (система «вспоминает», что давно вас не проверяла).\n"
    "3. В /top игроки сортируются не по чистому рейтингу, а по рейтинг − 2×RD — "
    "это не даёт новичку с одной победой резко залететь на первое место, пока "
    "система в нём не уверена.\n\n"
    "Ничьих в бильярде не бывает, поэтому каждая партия однозначно засчитывается "
    "как победа/поражение и пересчитывает рейтинг сразу после подтверждения."
)


@router.message(Command("faq"))
async def cmd_faq(message: Message) -> None:
    await message.answer(FAQ_TEXT)
