from __future__ import annotations

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

router = Router(name="faq")

FAQ_TEXT = (
    "📋 Команды\n\n"
    "/start\n"
    "Регистрация в системе рейтинга. Нужно быть добавленным администратором "
    "через /adduser — после этого /start покажет приветствие и подхватит ваш "
    "username.\n\n"
    "/score @игрок1 @игрок2 <тип> <счёт партий> <счёт1> [<счёт2> ...]\n"
    "Заявить результат матча — сразу в этот чат, без подтверждения. Заявить "
    "может любой участник, не только сами игроки.\n"
    "• <тип> — moscow/москва или america/америка.\n"
    "• <счёт партий> — сводный счёт X:Y (сколько партий выиграл каждый), "
    "нужен только для проверки.\n"
    "• <счётN> — счёт по шарам каждой сыгранной партии, например 8:7. Именно "
    "партии считаются в рейтинге, счёт по шарам идёт в статистику.\n"
    "Пример: /score @alex @petya moscow 2:0 8:7 8:6\n\n"
    "/cancel [session_id]\n"
    "Отменить свою последнюю заявку (или конкретную по session_id) и "
    "пересчитать рейтинг без неё. Отменить может только тот, кто её вносил.\n\n"
    "/top\n"
    "Таблица лидеров.\n\n"
    "/stats [@игрок]\n"
    "Статистика — своя или указанного игрока: рейтинг, W/L, последние матчи.\n\n"
    "/history @игрок\n"
    "История личных встреч с игроком: тип игры и счёт по шарам каждой партии.\n\n"
    "/faq\n"
    "Эта справка.\n\n"
    "❓ Как считается рейтинг\n\n"
    "Мы используем систему Glicko-2 — она сложнее обычного Эло, но даёт более "
    "честную оценку, особенно для новичков и тех, кто давно не играл.\n\n"
    "У каждого игрока есть три числа:\n"
    "• Рейтинг — сила игры (старт 1500).\n"
    "• RD (rating deviation) — «неуверенность» в рейтинге. У новичка RD большой "
    "(350) — система ещё мало о нём знает. Чем больше сыграно матчей, тем RD ниже.\n"
    "• σ (волатильность) — насколько нестабильно играет человек.\n\n"
    "Правила:\n"
    "1. Победа над сильным соперником даёт больше очков, чем победа над слабым.\n"
    "2. Если вы долго не играли — ваш RD подрастает, и следующий матч сильнее "
    "повлияет на рейтинг (система «вспоминает», что давно вас не проверяла).\n"
    "3. В /top игроки сортируются не по чистому рейтингу, а по рейтинг − 2×RD — "
    "это не даёт новичку с одной победой резко залететь на первое место, пока "
    "система в нём не уверена.\n\n"
    "Ничьих в бильярде не бывает, поэтому каждая партия однозначно засчитывается "
    "как победа/поражение и сразу пересчитывает рейтинг."
)


@router.message(Command("faq"))
async def cmd_faq(message: Message) -> None:
    await message.answer(FAQ_TEXT)
